/**
  ******************************************************************************
  * @file    dht22.h
  * @brief   DHT22 温湿度传感器驱动对外接口（单总线，数据脚 PC15）
  * @note    ⚠ PC15 与 PC14 同属 RTC 域：本工程必须保持 LSE 关闭，
  *          否则该引脚被 RTC 占用，驱动失效（继电器同理）。
  ******************************************************************************
  */
#ifndef __DHT22_H
#define __DHT22_H

#include "stm32f1xx_hal.h"

/************************* 引脚配置 *************************/
/* DHT22 数据线接 MCU 的 PC15（对照节点板原理图 DHT22 网络）。
 * ⚠ 底板数据线无外部上拉，依赖传感器模块自带上拉电阻（4.7k~10k）。 */
#define DHT22_GPIO_PORT    GPIOC
#define DHT22_GPIO_PIN     GPIO_PIN_15

/************************* 函数声明 *************************/
// 初始化DHT22引脚
void DHT22_Init(void);

// 读取DHT22温湿度数据
// 参数：temp-温度存储地址（单位：℃，精度0.1℃），humi-湿度存储地址（单位：%RH，精度0.1%）
// 返回值：0-读取成功，1/2-起始应答超时，3-数据接收或校验失败
uint8_t DHT22_ReadData(float *temp, float *humi);

#endif
